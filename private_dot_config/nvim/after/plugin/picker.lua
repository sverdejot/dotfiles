local fzf = require("fzf-lua")
vim.keymap.set("n", "<leader>ff", fzf.git_files, { desc = "Git files" })
vim.keymap.set("n", "<leader>fp", fzf.files, { desc = "Files" })
vim.keymap.set("n", "<leader>fs", fzf.live_grep, { desc = "Live grep" })
vim.keymap.set("n", "<leader>fw", fzf.grep_cword, { desc = "Grep word under cursor" })
vim.keymap.set("n", "<leader>fb", fzf.buffers, { desc = "Buffers" })
vim.keymap.set("n", "<leader>fh", fzf.helptags, { desc = "Help" })
vim.keymap.set("n", "<leader>fr", fzf.resume, { desc = "Resume last picker" })
vim.keymap.set("n", "<leader>fd", fzf.diagnostics_document, { desc = "Diagnostics" })
